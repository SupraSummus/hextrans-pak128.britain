# Tile raster width (output image pixel width for a single hex cell).
# `u = W/4` is the natural lattice unit and drops into the pakset's
# 128x128 cell layout.  Override via --w for other sizes.
DEFAULT_W = 128

# Per-step logical height; matches `env_t::pak_tile_height_step`
# (8 since the 2013 "Pak128 Half Height Conversion").  Combined with
# the unhalved `hex_height_raster_scale_y` this gives a 16-pixel screen
# lift per step at `W = 128`, the legacy pre-hex pak128 z scale.
HEIGHT_STEP = 8

# World-coords corner radius (one entry-edge length).  Bakers express
# asset dimensions in these units so the camera math doesn't depend on W.
# Re-exported from `pak.way` so the constant has a single source of truth
# and `pak.way` (pure-Python ribi vocab + hex geometry) doesn't have to
# pull in numpy via this module just to read it.
from .way import HEX_TILE_RADIUS  # noqa: E402,F401

# Pixel lift per world-z unit, shared with pak128 square dimetric so a
# given 3D part has comparable on-screen height in both projections.
PIXELS_PER_UNIT = DEFAULT_W / math.sqrt(2.0)


def engine_z_per_step(height_step: int = 1, w: int = DEFAULT_W) -> float:
    """World-z value whose hex projection lifts the screen by `height_step`
    engine height steps.  A bespoke render that wants its sloped sprite
    to align with the engine's ground rendering tilts world-z by this
    amount across one height-step's worth of slope.  Engine callers
    pass `z * TILE_HEIGHT_STEP` into `hex_height_raster_scale_y` (see
    `display/viewport.cc`); we mirror that here — a height_step of 1
    is `HEIGHT_STEP` raster units, ~16 px lift at W=128.
    """
    return hex_height_raster_scale_y(height_step * HEIGHT_STEP, w) / PIXELS_PER_UNIT

# Upstream Britain blends are authored against a fixed ortho camera
# with this scale rendering to 128x128 px (per the pak128.Britain
# contributing-graphics thread).  See `INTRA_TILE_PER_BLEND_UNIT`
# below for the consequence.
UPSTREAM_ORTHO_SCALE = 24.0


# ---- Coord systems --------------------------------------------------------
#
# Three coord systems show up in the bake pipeline; mixing them up is the
# usual source of "the strand renders 5x too big / too small" bugs.
#
# * **Tile coords** — integers.  Adjacent tile is `(x+1, y)` in either
#   hex or square; no projection difference lives here.  Outside this
#   module's scope.
# * **Intra-tile coords** — continuous within one tile.  Tile edge =
#   1 intra-tile unit in both projections (`HEX_TILE_RADIUS = 1` for
#   hex's entry-edge length, also the square tile side).  This is
#   where the cross-projection invariant holds: a way of width 0.4
#   spans 40% of an edge in *both* projections, so the way is
#   complete at every tile boundary regardless of which view the
#   game is rendered through.
# * **Blend coords** — upstream pak128.Britain's authoring frame
#   where `ortho_scale = UPSTREAM_ORTHO_SCALE` is the 15 m ruler.
#   The blend's native unit doesn't equal the intra-tile unit; the
#   conversion below.
#
# The conversion that lands the blend's authored sizes (rail gauge,
# tie pitch, ballast extent, vehicle dimensions) at the right
# intra-tile size is:

INTRA_TILE_PER_BLEND_UNIT = (2.0 * HEX_TILE_RADIUS) / UPSTREAM_ORTHO_SCALE
# = 1/12 at the current pakset constants.  This is the same ratio
# `pak.render::_compute_fit` applies under `fit_kind="hex"` for
# vehicles, and the same ratio the way bake will switch to once
# multi-atom-per-chord composition lands (TODO.md → "Way multi-
# atom-per-chord composition").


