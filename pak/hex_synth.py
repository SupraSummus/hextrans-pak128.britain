# Tile corner positions in world XY.  Hex circumradius `HEX_TILE_RADIUS = 1`
# so corners sit at distance 1 from origin and 1 world unit = 1 edge length.
HEX_CORNER_XY = [
    ( 1.0,        0.0      ),  # E   (0)
    ( 0.5,       -_SQRT3 / 2.0),  # SE  (1)
    (-0.5,       -_SQRT3 / 2.0),  # SW  (2)
    (-1.0,        0.0      ),  # W_C (3)
    (-0.5,        _SQRT3 / 2.0),  # NW  (4)
    ( 0.5,        _SQRT3 / 2.0),  # NE  (5)
]

# Touched-edge corner indices per axis: `((a0, a1), (b0, b1))`.
AXIS_EDGE_CORNERS = {
    NS:    ((NW,  NE), (SE, SW )),
    NE_SW: ((NE,  E ), (SW, W_C)),
    NW_SE: ((W_C, NW), (E,  SE )),
}

# Off-axis corners per axis: `(off_pos, off_neg)`.
AXIS_OFF_AXIS_CORNERS = {
    NS:    (E,  W_C),
    NE_SW: (SE, NW ),
    NW_SE: (NE, SW ),
}


def axis_corners(slope: int, axis: int):
    """Return `(a0, a1, b0, b1)` corner heights for `axis` on `slope`."""
    ch = decode_corner_heights(slope)
    (a0_i, a1_i), (b0_i, b1_i) = AXIS_EDGE_CORNERS[axis]
    return ch[a0_i], ch[a1_i], ch[b0_i], ch[b1_i]


def axis_h_way(slope: int, axis: int):
    """Return `(h_edge1, h_edge2)` for the way's chord on `axis`, or
    `None` if the axis is not way-buildable on `slope`."""
    a0, a1, b0, b1 = axis_corners(slope, axis)
    if a0 != a1 or b0 != b1:
        return None
    if abs(a0 - b0) <= 2:
        return a0, b0
    return None


def axis_edge_midpoints(axis: int):
    """`(mp1, mp2)` for the touched-edge midpoints (world XY)."""
    (a0_i, a1_i), (b0_i, b1_i) = AXIS_EDGE_CORNERS[axis]
    mp1 = ((HEX_CORNER_XY[a0_i][0] + HEX_CORNER_XY[a1_i][0]) / 2.0,
           (HEX_CORNER_XY[a0_i][1] + HEX_CORNER_XY[a1_i][1]) / 2.0)
    mp2 = ((HEX_CORNER_XY[b0_i][0] + HEX_CORNER_XY[b1_i][0]) / 2.0,
           (HEX_CORNER_XY[b0_i][1] + HEX_CORNER_XY[b1_i][1]) / 2.0)
    return mp1, mp2


def axis_unit_vector(axis: int):
    mp1, mp2 = axis_edge_midpoints(axis)
    dx, dy = mp2[0] - mp1[0], mp2[1] - mp1[1]
    n = math.sqrt(dx * dx + dy * dy)
    return (dx / n, dy / n)


def axis_perp_vector(axis: int):
    """Unit perpendicular (90° CCW from the axis direction)."""
    ux, uy = axis_unit_vector(axis)
    return (-uy, ux)


# ---- Slope validity -------------------------------------------------------

def slope_is_valid(slope: int) -> bool:
    """Whether a raw slope_t encoding is a normalised pakset slope."""
    ch = decode_corner_heights(slope)
    if min(ch) != 0:
        return False
    for i in range(CORNER_COUNT):
        j = (i + 1) % CORNER_COUNT
        if ch[i] > ch[j] + 1 or ch[j] > ch[i] + 1:
            return False
    return True


def iter_valid_slopes():
    for slope in range(4096):
        if slope_is_valid(slope):
            yield slope


def slope_is_way(slope: int) -> bool:
    """Whether a way (road, rail, …) can be laid across this hex slope."""
    ch = decode_corner_heights(slope)
    return (_is_way_axis(ch, ch[NW], ch[NE], ch[SE], ch[SW]) or
            _is_way_axis(ch, ch[NE], ch[E],  ch[SW], ch[W_C]) or
            _is_way_axis(ch, ch[W_C], ch[NW], ch[E], ch[SE]))


def _is_way_axis(ch: list[int], a0: int, a1: int, b0: int, b1: int) -> bool:
    if a0 == a1 and b0 == b1 and abs(a0 - b0) <= 1:
        return True  # ramp
    if any(c >= 2 for c in ch):
        return False  # double-corner: only the ramp case admits a way
    a_lo, a_hi = min(a0, a1), max(a0, a1)
    b_lo, b_hi = min(b0, b1), max(b0, b1)
    return max(a_lo, b_lo) <= min(a_hi, b_hi)


# ---- Lambert lighting (from synth_geometry.h) -----------------------------

LIGHT = (-1.0, 1.0, 2.0)


def lambert_brightness(nx: float, ny: float, nz: float) -> int:
    Lx, Ly, Lz = LIGHT
    L_norm = math.sqrt(Lx * Lx + Ly * Ly + Lz * Lz)
    flat_cos = Lz / L_norm

    n_norm = math.sqrt(nx * nx + ny * ny + nz * nz)
    if n_norm <= 0.0:
        return 256
    cos_theta = (nx * Lx + ny * Ly + nz * Lz) / (n_norm * L_norm)
    brightness = 256 + int((cos_theta - flat_cos) * 384.0)
    if brightness < 128:
        brightness = 128
    if brightness > 352:
        brightness = 352
    return brightness


