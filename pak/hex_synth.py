CLIFF_WALL_ENDPOINTS = (
    (W_C, NW),  # wall 0: NW edge
    (NW,  NE),  # wall 1: N  edge
    (NE,  E ),  # wall 2: NE edge
    (E,   SE),  # wall 3: SE edge
    (SE,  SW),  # wall 4: S  edge
    (SW,  W_C), # wall 5: SW edge
)
CLIFF_IMAGE_COUNT = 11  # per-wall image slots; index 0 = "no cliff"


def decode_cliff_index(index: int) -> tuple[int, int]:
    """`(h1, h2)` for a cliff cell's two endpoint lifts.

    Indices 1..8 are the standard `index = h1 + 3*h2` encoding;
    indices 9 and 10 are placeholder half-cliffs for the legacy
    double-height notch.
    """
    if index == 10:
        return 1, 0
    if index == 9:
        return 0, 1
    return index % 3, index // 3


def render_cliff_cell(wall: int, h1: int, h2: int, color,
                      geom: HexGeom | None = None) -> "np.ndarray":
    """Render one cliff-face cell into a HxWx4 RGBA buffer."""
    if geom is None:
        geom = HexGeom()

    buf = np.zeros((geom.h, geom.w, 4), dtype=np.uint8)
    if h1 == 0 and h2 == 0:
        return buf

    a, b = CLIFF_WALL_ENDPOINTS[wall]
    ax, ay = geom.vx[a], geom.vy_base[a]
    bx, by = geom.vx[b], geom.vy_base[b]

    xs = [ax, bx, bx,                   ax                  ]
    ys = [ay, by, by - h2 * geom.lift,  ay - h1 * geom.lift ]
    fill_polygon(buf, xs, ys, color)
    seal_horizontal_edges(buf, xs, ys, color)
    return buf


