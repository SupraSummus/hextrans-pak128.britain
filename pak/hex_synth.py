def _chords_cross(c1, c2) -> bool:
    a, b = sorted(c1)
    c, d = sorted(c2)
    return (a < c < b < d) or (c < a < d < b)


def _compute_regions_from_chord_mask(geom, mask: int):
    """Walk `geom.all_chords` masked by `mask`, returning the polygon
    regions or `None` if the mask is inconsistent.

    Mirrors the engine's `synth_plane_partition.h::compute_regions_from_chord_mask`,
    parameterised over `geom.corner_count` (4 for square, 6 for hex) and
    `geom.all_chords`."""
    n = geom.corner_count
    chords = geom.all_chords
    regions: list[list[int]] = [list(range(n))]
    for ci in range(len(chords)):
        if not (mask & (1 << ci)):
            continue
        a, b = chords[ci]
        split_idx = -1
        for ri, reg in enumerate(regions):
            if a in reg and b in reg:
                split_idx = ri
                break
        if split_idx < 0 or len(regions) >= n:
            return None
        reg = regions[split_idx]
        ai = reg.index(a)
        bi = reg.index(b)
        s = min(ai, bi)
        e = max(ai, bi)
        r1 = reg[s:e + 1]
        r2 = reg[e:] + reg[:s + 1]
        if len(r1) > n or len(r2) > n:
            return None
        regions[split_idx] = r1
        regions.append(r2)
    return regions


def _region_coplanar(geom, region: list[int], ch: list[int]) -> bool:
    n = len(region)
    if n <= 3:
        return True
    px = [geom.corner_projected_xy[i][0] for i in range(geom.corner_count)]
    py = [geom.corner_projected_xy[i][1] for i in range(geom.corner_count)]
    for a in range(n):
        for b in range(a + 1, n):
            for c in range(b + 1, n):
                for d in range(c + 1, n):
                    ia, ib, ic, id_ = region[a], region[b], region[c], region[d]
                    v1x = px[ib] - px[ia]
                    v1y = py[ib] - py[ia]
                    v1z = ch[ib] - ch[ia]
                    v2x = px[ic] - px[ia]
                    v2y = py[ic] - py[ia]
                    v2z = ch[ic] - ch[ia]
                    v3x = px[id_] - px[ia]
                    v3y = py[id_] - py[ia]
                    v3z = ch[id_] - ch[ia]
                    det = (v1x * (v2y * v3z - v2z * v3y)
                           - v1y * (v2x * v3z - v2z * v3x)
                           + v1z * (v2x * v3y - v2y * v3x))
                    if det != 0:
                        return False
    return True


def _region_flat_horizontal(region: list[int], ch: list[int]) -> bool:
    return all(ch[v] == ch[region[0]] for v in region)


def _region_projected_area2(geom, region: list[int]) -> int:
    a2 = 0
    n = len(region)
    px = [geom.corner_projected_xy[i][0] for i in range(geom.corner_count)]
    py = [geom.corner_projected_xy[i][1] for i in range(geom.corner_count)]
    for i in range(n):
        j = (i + 1) % n
        a2 += (px[region[i]] * py[region[j]]
               - px[region[j]] * py[region[i]])
    return abs(a2)


def find_min_partition(slope: int, geom=None) -> list[list[int]]:
    """Engine-equivalent minimum-region partition for a slope.

    `geom` selects the projection (defaults to `HexGeom()`).  The
    algorithm is projection-independent: it sweeps every chord-mask
    subset of `geom.all_chords`, drops masks with crossing chords or
    non-coplanar regions, and minimises (region count, -flat_area).
    """
    if geom is None:
        geom = HexGeom()
    ch = geom.decode_corner_heights(slope)
    chords = geom.all_chords
    best: list[list[int]] | None = None
    best_count = geom.corner_count + 1
    best_flat_area = -1

    for mask in range(1 << len(chords)):
        chords_set = [chords[i] for i in range(len(chords)) if mask & (1 << i)]
        ok = True
        for i in range(len(chords_set)):
            for j in range(i + 1, len(chords_set)):
                if _chords_cross(chords_set[i], chords_set[j]):
                    ok = False
                    break
            if not ok:
                break
        if not ok:
            continue

        cand = _compute_regions_from_chord_mask(geom, mask)
        if cand is None:
            continue
        if not all(_region_coplanar(geom, r, ch) for r in cand):
            continue

        flat_area = sum(_region_projected_area2(geom, r)
                        for r in cand if _region_flat_horizontal(r, ch))
        if (len(cand) < best_count
                or (len(cand) == best_count and flat_area > best_flat_area)):
            best = cand
            best_count = len(cand)
            best_flat_area = flat_area
            if best_count == 1:
                break

    return best if best is not None else [list(range(geom.corner_count))]


def trivial_partition(geom=None) -> list[list[int]]:
    if geom is None:
        geom = HexGeom()
    return [list(range(geom.corner_count))]


# ---- Polygon fill (independent re-implementation of synth_overlay.cc) -----

def fill_polygon(buf: np.ndarray, xs: list[int], ys: list[int],
                 color_rgb: tuple[int, int, int]):
    """Even-odd half-open scanline fill into an HxWx4 RGBA buffer."""
    h, w, _ = buf.shape
    n = len(xs)
    y_min = max(0, min(ys))
    y_max = min(h - 1, max(ys))

    for y in range(y_min, y_max + 1):
        xints: list[int] = []
        for i in range(n):
            j = (i + 1) % n
            ya, yb = ys[i], ys[j]
            if ya == yb:
                continue  # skip horizontal edges (parity)
            y_lo = min(ya, yb)
            y_hi = max(ya, yb)
            if y < y_lo or y >= y_hi:
                continue
            xa, xb = xs[i], xs[j]
            num = (y - ya) * (xb - xa)
            den = (yb - ya)
            q = abs(num) // abs(den)
            if (num < 0) ^ (den < 0):
                q = -q
            xints.append(xa + q)
        xints.sort()
        for k in range(0, len(xints) - 1, 2):
            x0 = max(0, xints[k])
            x1 = min(w - 1, xints[k + 1])
            if x0 <= x1:
                buf[y, x0:x1 + 1, 0] = color_rgb[0]
                buf[y, x0:x1 + 1, 1] = color_rgb[1]
                buf[y, x0:x1 + 1, 2] = color_rgb[2]
                buf[y, x0:x1 + 1, 3] = 255


def seal_horizontal_edges(buf: np.ndarray, xs: list[int], ys: list[int],
                          color_rgb: tuple[int, int, int]):
    """Fill horizontal polygon edges that the parity scanline skips."""
    h, w, _ = buf.shape
    n = len(xs)
    for i in range(n):
        j = (i + 1) % n
        if ys[i] != ys[j]:
            continue
        y = ys[i]
        if y < 0 or y >= h:
            continue
        x0 = min(xs[i], xs[j])
        x1 = max(xs[i], xs[j])
        x0 = max(0, x0)
        x1 = min(w - 1, x1)
        buf[y, x0:x1 + 1, 0] = color_rgb[0]
        buf[y, x0:x1 + 1, 1] = color_rgb[1]
        buf[y, x0:x1 + 1, 2] = color_rgb[2]
        buf[y, x0:x1 + 1, 3] = 255


# ---- Line drawing (from synth_overlay.cc draw_line) -----------------------

def draw_line(buf: np.ndarray, x0: int, y0: int, x1: int, y1: int,
              color_rgb: tuple[int, int, int]):
    """Bresenham line into an HxWx4 RGBA buffer with full-alpha output."""
    h, w, _ = buf.shape
    dx = abs(x1 - x0)
    dy = -abs(y1 - y0)
    sx = 1 if x0 < x1 else -1
    sy = 1 if y0 < y1 else -1
    err = dx + dy
    while True:
        if 0 <= x0 < w and 0 <= y0 < h:
            buf[y0, x0, 0] = color_rgb[0]
            buf[y0, x0, 1] = color_rgb[1]
            buf[y0, x0, 2] = color_rgb[2]
            buf[y0, x0, 3] = 255
        if x0 == x1 and y0 == y1:
            break
        e2 = 2 * err
        if e2 >= dy:
            err += dy
            x0 += sx
        if e2 <= dx:
            err += dx
            y0 += sy


# ---- Per-pixel barycentric helpers (shared by alpha-bake renderers) -------

def hash_noise01(x: np.ndarray, y: np.ndarray) -> np.ndarray:
    """Vectorised position-deterministic noise in `[0.0, 1.0)`."""
    h = ((x.astype(np.uint32) * np.uint32(73856093))
         ^ (y.astype(np.uint32) * np.uint32(19349663)))
    h ^= h >> np.uint32(13)
    h *= np.uint32(1274126177)
    h ^= h >> np.uint32(16)
    return ((h & np.uint32(0xFFFF)).astype(np.float32)
            / np.float32(65536.0))


def centre_fan_field(slope: int, corner_values, centre_value: float,
                     geom) -> np.ndarray:
    """Per-pixel barycentric mix over the slope's centre-fan triangles."""
    vx = np.array(geom.vx, dtype=np.float32)
    vy = np.array(geom.lifted_vy(slope), dtype=np.float32)
    weight = np.asarray(corner_values, dtype=np.float32)

    cx = float(vx.mean())
    cy = float(vy.mean())
    cw = float(centre_value)

    xs = np.arange(geom.w, dtype=np.float32) + 0.5
    ys = np.arange(geom.h, dtype=np.float32) + 0.5
    px, py = np.meshgrid(xs, ys)

    field = np.full((geom.h, geom.w), cw, dtype=np.float32)
    assigned = np.zeros((geom.h, geom.w), dtype=bool)

    n = geom.corner_count
    for i in range(n):
        j = (i + 1) % n
        ax, ay, aw = vx[i], vy[i], weight[i]
        bx, by, bw = vx[j], vy[j], weight[j]
        denom = (by - cy) * (ax - cx) + (cx - bx) * (ay - cy)
        if denom == 0.0:
            continue
        u = ((by - cy) * (px - cx) + (cx - bx) * (py - cy)) / denom
        v = ((cy - ay) * (px - cx) + (ax - cx) * (py - cy)) / denom
        w = 1.0 - u - v
        in_tri = (u >= 0) & (v >= 0) & (w >= 0) & ~assigned
        field[in_tri] = (u[in_tri] * aw + v[in_tri] * bw + w[in_tri] * cw)
        assigned |= in_tri

    return field


def iter_region_polygons(slope: int, geom):
    """Yield `(region, xs, ys)` for each polygon in `find_min_partition(slope)`."""
    vy = geom.lifted_vy(slope)
    for region in find_min_partition(slope, geom):
        if len(region) < 3:
            continue
        xs = [geom.vx[i] for i in region]
        ys = [vy[i] for i in region]
        yield region, xs, ys


def face_normal_brightness(pts) -> int:
    """Lambert brightness (256 = 1.0×) for a polygonal face given its
    vertices in the engine's Lambert frame."""
    p0 = pts[0]
    for k in range(2, len(pts)):
        p1, p2 = pts[k - 1], pts[k]
        ax, ay, az = p1[0] - p0[0], p1[1] - p0[1], p1[2] - p0[2]
        bx, by, bz = p2[0] - p0[0], p2[1] - p0[1], p2[2] - p0[2]
        nx = ay * bz - az * by
        ny = az * bx - ax * bz
        nz = ax * by - ay * bx
        if nx == 0.0 and ny == 0.0 and nz == 0.0:
            continue
        if nz < 0.0:
            nx, ny, nz = -nx, -ny, -nz
        return lambert_brightness(nx, ny, nz)
    return lambert_brightness(0.0, 0.0, 1.0)


def region_brightness(region: list[int], slope: int, geom) -> int:
    """Lambert brightness (256 = 1.0×) for one coplanar region."""
    ch = geom.decode_corner_heights(slope)
    vy = geom.lifted_vy(slope)
    pts = [(geom.vx[i], vy[i], ch[i] * geom.lift) for i in region]
    return face_normal_brightness(pts)


def silhouette_mask(slope: int, geom) -> np.ndarray:
    """Boolean (H, W) mask of pixels inside the slope silhouette."""
    buf = np.zeros((geom.h, geom.w, 4), dtype=np.uint8)
    sentinel = (1, 1, 1)
    for _region, xs, ys in iter_region_polygons(slope, geom):
        fill_polygon(buf, xs, ys, sentinel)
        seal_horizontal_edges(buf, xs, ys, sentinel)
    return buf[..., 3] != 0


def rasterise_outline(buf: np.ndarray, geom, slope: int,
                      path, color_rgb: tuple[int, int, int],
                      closed: bool):
    """Walk `path` (a sequence of corner indices), drawing each edge."""
    vy = geom.lifted_vy(slope)
    n_edges = len(path) if closed else len(path) - 1
    for i in range(n_edges):
        a = path[i]
        b = path[(i + 1) % len(path)]
        draw_line(buf, geom.vx[a], vy[a], geom.vx[b], vy[b], color_rgb)


# ---- Atlas + bake helpers -------------------------------------------------
#
# `bake_pakset` runs the bake → atlas + .dat pipeline shared by every
# parametric ground family.  Each per-asset baker is a single
# `grounds/<asset>.py` file (Britain convention — script and emitted
# .dat/.png siblings under `grounds/`) that defines a `render_cell`
# function and calls `bake_pakset` from `__main__`.


def repo_root_for(script_path: Path) -> Path:
    """Walk up from `script_path` until we find a Makefile (the repo root
    marker for this pak).  Used purely for pretty `relative_to(...)`
    printouts in the stderr summary and the .dat header comment."""
    for parent in script_path.parents:
        if (parent / "Makefile").is_file():
            return parent
    return script_path.parent


def slope_keyed_entries(halves: int = 1, slope_filter=None):
    """Default `iter_entries` for slope-keyed assets.

    Uses `geom.iter_valid_slopes()` / `geom.decode_corner_heights()`,
    so the same factory drives both `HexGeom` and `SquareGeom` runs;
    the per-cell comment names corners via `geom.corner_labels`.
    """
    def gen(geom):
        labels = geom.corner_labels
        for half in range(halves):
            for slope in geom.iter_valid_slopes():
                if slope_filter is not None and not slope_filter(slope):
                    continue
                ch = geom.decode_corner_heights(slope)
                side = "" if halves == 1 else ("front " if half == 0 else "back ")
                inner = " ".join(f"{labels[i]}={ch[i]}" for i in range(geom.corner_count))
                comment = f"{side}corners=({inner})"
                yield slope, half, (slope, half), comment
    return gen


def bake_pakset(*, script_path: Path, asset_name: str, obj_name: str,
                render_cell, iter_entries,
                default_cols: int = 12, argv=None):
    """Run argparse, bake atlas + .dat for one synth-overlay family.

    Hex is the production projection; `--projection square` swaps in
    `square_synth.SquareGeom` for the upstream-Britain pixel-diff
    harness (`pak/diff_grounds.py`).
    """
    p = argparse.ArgumentParser()
    p.add_argument("--w", type=int, default=DEFAULT_W,
                   help=f"raster tile width (default {DEFAULT_W})")
    p.add_argument("--cols", type=int, default=default_cols,
                   help=f"atlas columns (default {default_cols})")
    p.add_argument("--out-dir", type=Path, default=script_path.parent,
                   help="output directory (default: the script's own dir)")
    p.add_argument("--projection", choices=("hex", "square"), default="hex",
                   help="ground geom (hex by default; square for upstream diff)")
    args = p.parse_args(argv)

    args.out_dir.mkdir(parents=True, exist_ok=True)

    if args.projection == "square":
        from pak.square_synth import SquareGeom
        geom = SquareGeom(raster_w=args.w)
    else:
        geom = HexGeom(raster_w=args.w)
    entries = list(iter_entries(geom))
    n_entries = len(entries)
    rows = (n_entries + args.cols - 1) // args.cols
    cell_w, cell_h = geom.w, geom.h
    atlas = np.zeros((rows * cell_h, args.cols * cell_w, 4), dtype=np.uint8)

    rel_root = repo_root_for(script_path)
    script_rel = script_path.relative_to(rel_root)

    dat_lines = [
        f"# Generated by {script_rel.as_posix()} — do not edit by hand.",
        "Obj=ground",
        f"Name={obj_name}",
        "",
    ]

    for idx, (dat_typ, dat_stage, render_args, comment) in enumerate(entries):
        r, c = divmod(idx, args.cols)
        cell = render_cell(*render_args, geom=geom)
        atlas[r * cell_h:(r + 1) * cell_h,
              c * cell_w:(c + 1) * cell_w] = cell
        dat_lines.append(
            f"Image[{dat_typ}][{dat_stage}]={asset_name}.{r}.{c}\t# {comment}"
        )
    dat_lines.append("")

    png_path = args.out_dir / f"{asset_name}.png"
    dat_path = args.out_dir / f"{asset_name}.dat"
    from PIL import Image
    Image.fromarray(atlas, mode="RGBA").save(str(png_path))
    dat_path.write_text("\n".join(dat_lines))

    def _pretty(p: Path) -> str:
        try:
            return p.relative_to(rel_root).as_posix()
        except ValueError:
            return str(p)

    print(f"{script_rel.as_posix()}: wrote {n_entries} cells into "
          f"{_pretty(png_path)} "
          f"({args.cols}x{rows} atlas, {atlas.shape[1]}x{atlas.shape[0]} px)",
          file=sys.stderr)
    print(f"{script_rel.as_posix()}: wrote .dat with {n_entries} entries -> "
          f"{_pretty(dat_path)}",
          file=sys.stderr)
