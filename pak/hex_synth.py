"""Shared utilities for the hex pipeline.

Two consumers live in the same module:

* **Blender baker** (`pak/render.py`, `viewpoints.py`):
  pakset-wide projection constants for re-rendering upstream
  Pak128.Britain blends through the hex camera.  These don't appear
  in the regular pak128 sibling — they're Britain-specific blend
  calibration.

* **Parametric ground synth** (`grounds/<asset>/build_pakset.py`):
  per-slope geometry, per-region plane partition, polygon fill, atlas
  + .dat baker.  Mirrors the engine's `descriptor/synth_geometry.h` +
  `descriptor/synth_plane_partition.h`.  Ported from
  `hextrans-pak128/tools/threed/hex_synth.py`; keep the bottom half
  aligned with that file when constants drift, but the file has two
  Britain-only adjustments at the bottom of `bake_pakset` (the
  repo-root walk in `repo_root_for` looks for `.git` and the
  "Generated by" comment carries the `grounds/...` prefix — the
  regular pak puts its bakers under `landscape/grounds/`, this pak
  under `grounds/`).

Engine source-of-truth: `hextrans/src/simutrans/display/hex_proj.h`,
`display/synth_geometry.h`, `descriptor/synth_plane_partition.h`.
"""

